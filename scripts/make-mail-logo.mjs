// Renders the official OpSolid lockup (the paths in src/components/v7/Logo.tsx) as a small transparent PNG for
// mail, and writes it as base64 into src/lib/email/ack-logo.ts. The mail embeds it (Content-ID), so no mail
// links to a server. Copper, because a mail client in dark mode can turn the background dark: ink would vanish.
// usage: node scripts/make-mail-logo.mjs [<copy-of-the-png.png>]
// Needs playwright-core and a Chromium headless shell, like scripts/site-capture.mjs (PLAYWRIGHT_CORE).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
const PW =
  process.env.PLAYWRIGHT_CORE ||
  path.join(process.env.HOME, "Documents/Codex/Projects/Project_VERSO-opso-card/tools/opso-card/node_modules/playwright-core/index.mjs");
const { chromium } = await import(PW);

const WIDTH = 126; // CSS px in the mail, as in the site header
const HEIGHT = 30;
const SCALE = 3;
const COPPER = "#B5623A";

const source = fs.readFileSync(path.join(repo, "src/components/v7/Logo.tsx"), "utf8");
const block = (name) => {
  const m = new RegExp(`const ${name} =([\\s\\S]*?);\\n`).exec(source);
  if (!m) throw new Error(`${name} not found in Logo.tsx`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]).join("");
};
const d = block("MARK") + block("WORD");
if (!/viewBox="0 0 1259 300"/.test(source)) throw new Error("Logo.tsx viewBox changed");

const html = `<!doctype html><html><body style="margin:0;background:transparent">
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1259 300" width="${WIDTH}" height="${HEIGHT}" style="display:block">
<path fill="${COPPER}" fill-rule="evenodd" d="${d}"/></svg></body></html>`;

const cache = path.join(process.env.HOME, "Library/Caches/ms-playwright");
const shell = fs.readdirSync(cache).filter((x) => x.startsWith("chromium_headless_shell-")).sort().pop();
const browser = await chromium.launch({ executablePath: path.join(cache, shell, "chrome-headless-shell-mac-arm64/chrome-headless-shell") });
const page = await browser.newPage({ viewport: { width: WIDTH, height: HEIGHT }, deviceScaleFactor: SCALE });
await page.setContent(html);
const png = await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: WIDTH, height: HEIGHT } });
await browser.close();

const out = `// Generated by scripts/make-mail-logo.mjs from src/components/v7/Logo.tsx. Do not edit by hand.
// The official lockup in copper on a transparent ground, ${WIDTH * SCALE} x ${HEIGHT * SCALE} px, shown at ${WIDTH} x ${HEIGHT}.
export const ACK_LOGO = {
  cid: "opsolid-logo@opsolid.de",
  filename: "opsolid-logo.png",
  contentType: "image/png",
  width: ${WIDTH},
  height: ${HEIGHT},
  contentBase64:
    "${png.toString("base64")}",
} as const;
`;
fs.writeFileSync(path.join(repo, "src/lib/email/ack-logo.ts"), out);
if (process.argv[2]) fs.writeFileSync(path.resolve(process.argv[2]), png);
console.log(`ack-logo.ts written: ${png.length} bytes PNG, ${WIDTH * SCALE}x${HEIGHT * SCALE}`);
